// Draws every image into generated/ and writes README.md from data/.
// Runs on every push, every day, and after every Connect Four move.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { THEMES, hero, productCard, stats, stack, board, colButton, city } from './svg.mjs'
import * as P from '../data/profile.mjs'
import { ROWS, COLS } from './connect4.mjs'

const root = new URL('..', import.meta.url).pathname.replace(/\/$/, '')
const out = `${root}/generated`
mkdirSync(out, { recursive: true })

const state = JSON.parse(readFileSync(`${root}/game/state.json`, 'utf8'))
const st = existsSync(`${root}/data/stats.json`)
  ? JSON.parse(readFileSync(`${root}/data/stats.json`, 'utf8'))
  : { total: 0, weeks: [] }

const RAW = `https://raw.githubusercontent.com/${P.REPO}/main/generated`
const versions = {}

function save(name, draw) {
  for (const theme of ['dark', 'light']) {
    const svg = draw(THEMES[theme], theme)
    writeFileSync(`${out}/${name}-${theme}.svg`, svg)
    versions[`${name}-${theme}`] = createHash('sha1').update(svg).digest('hex').slice(0, 8)
  }
}

// Raw files are cached for a few minutes, so every URL carries a hash of its
// content. A changed image gets a new URL and shows up immediately.
const src = (name, theme) => `${RAW}/${name}-${theme}.svg?v=${versions[`${name}-${theme}`]}`
const pic = (name, alt, width) =>
  `<picture><source media="(prefers-color-scheme: dark)" srcset="${src(name, 'dark')}"><source media="(prefers-color-scheme: light)" srcset="${src(name, 'light')}"><img alt="${alt}" src="${src(name, 'dark')}" width="${width}"></picture>`

/* ------------------------------------------------------------- images */

save('hero', (t) => hero(t, { name: P.NAME, eyebrow: P.EYEBROW, roles: P.ROLES }))
for (const p of P.PRODUCTS) save(`product-${p.key}`, (t) => productCard(t, p, root))
save('stats', (t) => stats(t, P.STATS))
save('stack', (t, theme) => stack(t, P.STACK, P.STACK_LABEL, theme))
for (let c = 1; c <= COLS; c++) save(`col-${c}`, (t) => colButton(t, c))

const turnText = state.moves === 0
  ? 'Fresh board. You are red, drop the first disc.'
  : `Game #${state.game} · ${state.moves} discs played · your move`
save('connect4', (t) => board(t, state, { title: 'Connect Four vs my bot', sub: turnText, lastMove: state.lastMove }))

const last = state.games[0]
if (last) {
  save('connect4-last', (t) =>
    board(t, { board: last.board }, { title: 'Last game', sub: resultLine(last), win: last.win }))
}

const showCity = st.total >= P.CITY_MIN_CONTRIBUTIONS
if (st.weeks.length) save('city', (t) => city(t, st.weeks, st.total))

function resultLine(g) {
  const who = g.players.length ? g.players.map((p) => `@${p}`).slice(0, 3).join(', ') : 'visitors'
  if (g.result === 'human') return `${who} beat the bot in ${g.moves} moves`
  if (g.result === 'bot') return `The bot won in ${g.moves} moves against ${who}`
  return `Draw after ${g.moves} moves`
}

/* ------------------------------------------------------------- README */

const issue = (c) =>
  `https://github.com/${P.REPO}/issues/new?title=${encodeURIComponent(`connect4|drop|${c}`)}&body=${encodeURIComponent(
    `Press **Create** to drop your disc into column ${c}.\n\nThe bot answers within a minute and the board on the profile updates by itself. You can close this tab.`
  )}`

// komarev.com refuses GitHub's image proxy (404 through camo), so the
// counter moved to visitorbadge.io, which serves it.
const views = 'https://api.visitorbadge.io/api/visitors?path=med-aziz-kaboudi-profile&countColor=%232f81f7&style=for-the-badge&labelStyle=upper'
const badge = (label, color, logo, href) =>
  `<a href="${href}"><img src="https://img.shields.io/badge/${encodeURIComponent(label)}-${color}?style=for-the-badge&logo=${logo}&logoColor=white" alt="${label}"></a>`
const store = (p) =>
  [
    badge('App Store', '0D96F6', 'appstore', p.ios),
    badge('Google Play', '414141', 'googleplay', p.android),
    badge(p.site, p.colors[0].slice(1), 'googlechrome', p.url),
  ].join(' ')

const winners = Object.entries(state.wins).sort((a, b) => b[1] - a[1]).slice(0, 5)
const botWins = state.games.filter((g) => g.result === 'bot').length
const humanWins = state.games.filter((g) => g.result === 'human').length

const md = []
md.push(`<!-- Generated by scripts/render.mjs. Edit data/profile.mjs instead, this file is overwritten. -->`)
md.push(`<p align="center"><a href="${P.LINKS.portfolio}">${pic('hero', 'Mohamed Aziz Kaboudi, software engineer and founder', 1200)}</a></p>`)
md.push(`<p align="center">
  ${badge('Portfolio', '0E75B6', 'googlechrome', P.LINKS.portfolio)}
  ${badge('LinkedIn', '0A66C2', 'linkedin', P.LINKS.linkedin)}
  ${badge('Email', 'D14836', 'gmail', P.LINKS.email)}
  <img src="${views}" alt="Profile views">
</p>`)
md.push(P.ABOUT.map((l) => `<p align="center">${l.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')}</p>`).join('\n'))
md.push(`<p align="center">${pic('stats', 'Two apps live in stores, six years building, fifty plus projects, three hackathon placements', 1200)}</p>`)

md.push(`## 📱 My products`)
md.push(`<table><tr>
${P.PRODUCTS.map((p) => `<td width="50%" align="center"><a href="${p.url}">${pic(`product-${p.key}`, p.name, 600)}</a><br>${store(p)}</td>`).join('\n')}
</tr></table>`)
md.push(`<sub>Both designed, built, shipped and run by me: product, design, mobile, backend, infrastructure and the AI inside them. Owemie and Ömrüm are proprietary; their source is private and their names, logos and design may not be reused without written permission.</sub>`)

md.push(`## 🧰 Stack`)
md.push(`<p align="center">${pic('stack', 'TypeScript, Dart, Python, Kotlin, Swift, Flutter, React, Next.js, NestJS, PostgreSQL, Supabase, Ollama, PyTorch, Google Cloud, Docker and more', 1200)}</p>`)

md.push(`## 🎮 Beat my bot at Connect Four`)
md.push(`You play red against a bot that thinks five moves ahead. Pick a column below, press **Create** on the issue that opens, and within a minute a GitHub Action drops your disc, lets the bot answer and redraws this board. Everyone plays the same game.`)
md.push(`<p align="center">${pic('connect4', 'Current Connect Four board', 520)}</p>`)
md.push(`<p align="center">
${Array.from({ length: COLS }, (_, i) => `  <a href="${issue(i + 1)}">${pic(`col-${i + 1}`, `Drop in column ${i + 1}`, 64)}</a>`).join('\n')}
</p>`)
const recent = state.recent.length
  ? state.recent.slice(0, 5).map((r) => `[@${r.login}](https://github.com/${r.login}) → column ${r.col}`).join(' · ')
  : 'No moves yet. Be the first.'
md.push(`<p align="center"><sub><b>Latest moves:</b> ${recent}</sub></p>`)
md.push(`<p align="center"><sub><b>Score so far:</b> humans ${humanWins} · bot ${botWins}${winners.length ? ` · <b>Hall of fame:</b> ${winners.map(([l, n]) => `<a href="https://github.com/${l}">@${l}</a> (${n})`).join(', ')}` : ''}</sub></p>`)
if (last) {
  md.push(`<details><summary>Last finished game</summary><p align="center">${pic('connect4-last', resultLine(last), 420)}</p></details>`)
}

if (showCity) {
  md.push(`## 🏙️ My year in 3D`)
  md.push(`<p align="center">${pic('city', `${st.total} contributions in the last year as a 3D city`, 1200)}</p>`)
  md.push(`<p align="center"><picture><source media="(prefers-color-scheme: dark)" srcset="https://raw.githubusercontent.com/${P.REPO}/output/snake-dark.svg"><img alt="Snake eating my contributions" src="https://raw.githubusercontent.com/${P.REPO}/output/snake.svg"></picture></p>`)
}

md.push(`## 🏆 Hackathons & certifications`)
md.push(`| | Project | What it did |
|---|---|---|
${P.HACKATHONS.map(([a, b, c]) => `| ${a} | **${b}** | ${c} |`).join('\n')}`)
md.push(P.CERTS.map(([i, n, y]) => `\`${i}\` ${n} · ${y}`).join('<br>\n'))

md.push(`<p align="center"><sub>© ${new Date().getFullYear()} Mohamed Aziz Kaboudi · this profile draws itself: every image above is generated by code in this repo and refreshed by GitHub Actions · <a href="archive/v1/README.md">previous version</a></sub></p>`)

writeFileSync(`${root}/README.md`, md.join('\n\n') + '\n')
console.log(`rendered README, city ${showCity ? 'shown' : `hidden (${st.total} < ${P.CITY_MIN_CONTRIBUTIONS})`}`)
